def append(text):
    with LOG.open("a") as handle:
        handle.write(text)


def run(command, note):
    result = subprocess.run(
        command, shell=True, capture_output=True, text=True, timeout=120
    )
    body = result.stdout + result.stderr
    append("```console\n$ %s\n%s(exit %d)\n```\n\n" % (command, body, result.returncode))
    print("%-52s exit=%d %s" % (note, result.returncode, "PASS" if result.returncode == 0 else "FAIL"))
    return result.returncode


def main():
    LOG.write_text(HEADER)
    failures = 0
    results = []
    append("\n## Control matrix\n\n")
    append("| # | Guard | Break | Expected failing test |\n")
    append("|---|-------|-------|-----------------------|\n")
    for index, (label, breaker, expect, _) in enumerate(CONTROLS, start=1):
        append("| %d | %s | `%s` | `%s` |\n" % (index, label, breaker, expect))
    append("\n")

    for index, (label, breaker, expect, description) in enumerate(CONTROLS, start=1):
        append("\n## %d. Guard: %s\n\n" % (index, label))
        append("Break: `python3 /tmp/aep-lab/pilot/AE-neutral-1/%s` — %s.\n\n"
               % (breaker, description))
        append("Expected failure: `%s`\n\n" % expect)
        argv = (
            '%s negcontrol '
            "--file /tmp/aep-lab/pilot/AE-neutral-1/refunds.py "
            '--break-cmd "python3 /tmp/aep-lab/pilot/AE-neutral-1/%s" '
            '--test-cmd "%s" '
            '--expect "%s" '
            "--timeout 20"
        ) % (AEPKIT, breaker, TEST_CMD, expect)
        code = run(argv, label)
        failures += code != 0
        results.append((label, breaker, expect, code))

    append("\n## Result\n\n")
    if failures:
        append("%d of %d controls did NOT exit 0. The matrix is incomplete.\n"
               % (failures, len(CONTROLS)))
    else:
        append("All %d controls exited 0: each guard, when removed, makes the suite fail "
               "with the named test, and the suite is green again after `aepkit` restores "
               "`refunds.py` from its backup.\n" % len(CONTROLS))
        append("\n| # | Guard | aepkit exit |\n|---|-------|-------------|\n")
        for index, (label, breaker, expect, code) in enumerate(results, start=1):
            append("| %d | %s | %d |\n" % (index, label, code))
    return 1 if failures else 0


if __name__ == "__main__":
    sys.exit(main())
